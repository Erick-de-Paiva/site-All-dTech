ALL'DTECH - Termos e condições de entrega <br>

POLÍTICA DE ENTREGA <br>
1. Confirmação de Pagamento: 
O tempo de confirmação do pagamento é de até 24h para débito online, até 48h para cartões de crédito e até 72h para boleto bancário, antes do envio do produto. <br>
2. Métodos de Entrega: 
Oferecemos diversas opções de entrega para todo o território nacional, incluindo:
Entregas via Correios (SEDEX e PAC): Envio de segunda a sexta, até às 14h, sendo que após esse horário, o produto é despachado no dia útil seguinte.
Entrega por Transportadoras: Efetuada por parceiras, de segunda a sexta-feira, das 8h às 18h. Excepcionalmente, pode ocorrer aos sábados e domingos. <br>
3. Horário e Dias de Entrega:
As entregas são realizadas de segunda a sexta-feira, em horário comercial. 
Em algumas situações, especialmente durante grandes eventos como a Black Friday, as entregas podem ser realizadas excepcionalmente aos sábados, domingos e feriados. <br> 
4. Tentativas de Entrega:
Serão realizadas até três (3) tentativas de entrega no endereço informado, em dias alternados e com intervalo de até 48 horas. 
Caso as tentativas de entrega não sejam bem-sucedidas, o pedido retornará ao nosso centro de distribuição e será cancelado. <br>
5. Recebimento da Mercadoria: 
É indispensável que um responsável, maior de 18 anos e com documento de identificação, esteja no local para receber a mercadoria.
O recebimento também pode ser feito por porteiros de condomínios e familiares, mediante assinatura do comprovante. <br>
6. Condições de Não Aceitação da Entrega: 
Recuse o recebimento da mercadoria caso a embalagem esteja aberta ou avariada, o produto esteja danificado ou em desacordo com o pedido.
Nesse caso, anote o motivo da recusa no verso do DANFE (Documento Auxiliar da Nota Fiscal Eletrônica) e entre em contato conosco imediatamente. <br>
7. Serviços Não Incluídos na Entrega: 
Não realizamos montagens ou instalações, nem transporte do produto por escadas, janelas ou içamento.
A entrega não pode ser realizada em endereço diferente do que consta na nota fiscal (DANFE). <br>
8. Prazos e Atendimento: 
Para qualquer problema ou para informações sobre a entrega, entre em contato com o nosso setor de atendimento ao cliente.
É fundamental que os dados de endereço e telefone do seu cadastro estejam sempre atualizados para garantir o sucesso da entrega.
